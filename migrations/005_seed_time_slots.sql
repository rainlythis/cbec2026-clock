-- Attach any appointments that already exist to their cell. A row whose start
-- time matches no slot stays parked (slot_id IS NULL) rather than being
-- silently dropped - visible in the operator's parked tray, and not callable.
UPDATE appointments a
   SET slot_id          = s.id,
       original_slot_id = COALESCE(a.original_slot_id, s.id)
  FROM time_slots s
  JOIN table_days td
    ON td.event_date = s.event_date
   AND td.grid_key   = s.grid_key
 WHERE td.table_code    = a.table_code
   AND a.event_date     = s.event_date
   AND a.scheduled_start = s.starts_at
   AND a.slot_id IS NULL;
